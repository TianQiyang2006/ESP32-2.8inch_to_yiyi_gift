"""Build offline export resources from the existing HTML prototype and raw assets.

Run from any working directory: python design/build_designer.py
The generated bundle lets file:// users export one portable HTML without fetch.
"""
from pathlib import Path
import base64
import json
import re
import shutil
import mimetypes

ROOT = Path(__file__).resolve().parent
PROJECT = ROOT.parent


def main():
    prototype = (ROOT / 'prototype.html').read_text(encoding='utf-8')
    base_css = re.search(r'<style>(.*?)</style>', prototype, re.S).group(1)
    (ROOT / 'preview-base.css').write_text('/* Existing prototype foundations. Generated by build_designer.py. */\n' + base_css, encoding='utf-8')
    (ROOT / 'assets').mkdir(exist_ok=True)
    original_card = PROJECT / 'ui_design/ui_home/assets/image/cat_card.png'
    if original_card.exists():
        shutil.copyfile(original_card, ROOT / 'assets/cat-card.png')
    elif not (ROOT / 'assets/cat-card.png').exists():
        raise FileNotFoundError('Missing cached cat-card.png artwork')
    css = '\n'.join((ROOT / name).read_text(encoding='utf-8') for name in ['preview-base.css', 'app.css', 'calendar.css', 'studio.css', 'preview.css','postcard.css','weather-dashboard.css','holiday-dashboard.css','daily-dashboard.css','reading-dashboard.css','device-ui.css','message-board.css'])
    preview = (ROOT / 'preview.html').read_text(encoding='utf-8')
    body = re.search(r'<body>(.*?)<script', preview, re.S).group(1).strip()
    assets = {}
    files = [('assets/'+file.name, file) for file in sorted((ROOT/'assets').iterdir()) if file.suffix.lower() in ['.png','.jpg'] and '-draft' not in file.stem]
    files += [('../罗小黑gif和表情/' + file.name, file) for file in sorted((PROJECT / '罗小黑gif和表情').glob('*.gif'))]
    for key, file in files:
        mime = mimetypes.guess_type(file.name)[0]
        assets[key] = 'data:' + mime + ';base64,' + base64.b64encode(file.read_bytes()).decode('ascii')
    payload = {'css': css, 'body': body, 'model': (ROOT / 'designer-model.js').read_text(encoding='utf-8'), 'data': (ROOT / 'live-data.js').read_text(encoding='utf-8'), 'app': (ROOT / 'app.js').read_text(encoding='utf-8'), 'weatherUI': (ROOT / 'weather-dashboard.js').read_text(encoding='utf-8'), 'bridge': (ROOT / 'preview-bridge.js').read_text(encoding='utf-8'), 'assets': assets}
    payload['holidayCalendar'] = (ROOT / 'holiday-calendar.js').read_text(encoding='utf-8')
    payload['holidayUI'] = (ROOT / 'holiday-dashboard.js').read_text(encoding='utf-8')
    payload['dailyData'] = (ROOT / 'daily-data.js').read_text(encoding='utf-8')
    payload['dailyUI'] = (ROOT / 'daily-dashboard.js').read_text(encoding='utf-8')
    payload['readingData'] = (ROOT / 'reading-data.js').read_text(encoding='utf-8')
    payload['deviceLink'] = (ROOT / 'device-link.js').read_text(encoding='utf-8')
    payload['deviceUI'] = (ROOT / 'device-ui.js').read_text(encoding='utf-8')
    payload['messageUI'] = (ROOT / 'message-board.js').read_text(encoding='utf-8')
    payload['readingUI'] = (ROOT / 'reading-dashboard.js').read_text(encoding='utf-8')
    (ROOT / 'designer-bundle.js').write_text('// Generated offline export resources. Rebuild with python design/build_designer.py.\nwindow.YiyiExportSources=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print('Offline designer bundle ready; original GIF bytes preserved,', len(assets), 'assets.')


if __name__ == '__main__':
    main()
