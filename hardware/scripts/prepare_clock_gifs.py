"""Prepare the three retained clock GIFs for the 320x240 ESP32 desktop.

The clock owns the upper 87 pixels; GIFs retain their aspect ratio below it.
Black portrait margins are cropped once for the whole clip (never per frame).
Colour clips use 10 fps, a shared 64-colour palette and a mild median filter.
Their original running times are retained. Originals are never overwritten.
"""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = ROOT / 'Ui设计图片/时钟功能预设/1'
DEFAULT_OUTPUT = ROOT / 'hardware/arduino/yiyi_desk/src/pages/assets/clock_gifs'
# Preserve source identities so regenerating cannot reintroduce removed clips.
ACTIVE_GIFS = (
    (0, 'lv_0_20261028210454.gif'),
    (1, 'lv_0_20261028210512.gif'),
    (4, 'lv_0_20261028210538.gif'),
)


def prepare(source, destination):
    destination.mkdir(parents=True, exist_ok=True)
    report = []
    for number, filename in ACTIVE_GIFS:
        path = source / filename
        original = Image.open(path)
        frames, delays, bounds = [], [], None
        portrait = original.height > original.width
        colourful = path.stem.endswith(('210524', '210538'))
        for frame in range(original.n_frames):
            original.seek(frame)
            rgb = original.convert('RGB')
            frames.append(rgb)
            delays.append(original.info.get('duration', 70))
            if portrait:
                # These two portrait exports contain a mostly black lower
                # margin and a tiny corner mark, outside the expression area.
                area = rgb.crop((0, 0, rgb.width, rgb.height * 3 // 4))
                box = area.point(lambda x: 255 if x > 24 else 0).getbbox()
                if box:
                    bounds = box if bounds is None else (
                        min(bounds[0], box[0]), min(bounds[1], box[1]),
                        max(bounds[2], box[2]), max(bounds[3], box[3]))
        if bounds:
            bounds = (max(0, bounds[0]-12), max(0, bounds[1]-12),
                      min(original.width, bounds[2]+12), min(original.height, bounds[3]+12))
            frames = [frame.crop(bounds) for frame in frames]
        duration = sum(delays)
        if colourful:
            selected, timing, index, until = [], [], 0, delays[0]
            for at in range(0, duration, 100):
                while at >= until and index+1 < len(frames):
                    index += 1
                    until += delays[index]
                selected.append(frames[index])
                timing.append(min(100, duration-at))
            frames, delays = selected, timing
        size = ImageOps.contain(frames[0], (256, 143) if colourful else (274, 153)).size
        frames = [frame.resize(size, Image.Resampling.LANCZOS) for frame in frames]
        if colourful:
            frames = [frame.filter(ImageFilter.MedianFilter(3)) for frame in frames]
        count = min(12, len(frames))
        samples = Image.new('RGB', (size[0], size[1]*count))
        for i in range(count):
            samples.paste(frames[i*(len(frames)-1)//max(1, count-1)], (0, i*size[1]))
        palette = samples.quantize(colors=64, method=Image.Quantize.MEDIANCUT)
        frames = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in frames]
        gif = destination / f'clock_gif_{number}.gif'
        frames[0].save(gif, save_all=True, append_images=frames[1:], duration=delays,
                       loop=0, disposal=1, optimize=True)
        data = gif.read_bytes()
        symbol = f'clock_gif_{number}'
        lines = ['/* Generated by hardware/scripts/prepare_clock_gifs.py. */',
                 '#include "clock_gif_assets.h"', f'const uint8_t {symbol}[] = {{']
        lines += ['  '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0, len(data), 24)]
        lines += ['};', f'const size_t {symbol}_size = sizeof({symbol});', '']
        (destination / f'{symbol}.c').write_text('\n'.join(lines), encoding='utf-8')
        check = Image.open(gif)
        actual_duration = 0
        for i in range(check.n_frames):
            check.seek(i)
            actual_duration += check.info['duration']
        assert actual_duration == duration
        item = dict(symbol=symbol, source=path.name, sourceSha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                    size=size, frames=check.n_frames, durationMs=duration, bytes=len(data), crop=bounds,
                    sha256=hashlib.sha256(data).hexdigest())
        report.append(item)
        print(json.dumps(item, ensure_ascii=False), flush=True)
    assert len(report) == len(ACTIVE_GIFS), 'All retained GIFs must be generated'
    header = ['#pragma once', '#include <stdint.h>', '#include <stddef.h>',
              '#ifdef __cplusplus', 'extern "C" {', '#endif']
    for item in report:
        symbol = item['symbol']
        header += [f'extern const uint8_t {symbol}[];', f'extern const size_t {symbol}_size;']
    header += ['#ifdef __cplusplus', '}', '#endif', '']
    (destination / 'clock_gif_assets.h').write_text('\n'.join(header), encoding='utf-8')
    (destination / 'manifest.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print('Total embedded GIF bytes:', sum(item['bytes'] for item in report))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=DEFAULT_INPUT)
    parser.add_argument('--out', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    prepare(args.input, args.out)
