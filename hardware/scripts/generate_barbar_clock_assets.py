#!/usr/bin/env python3
"""Extract the upstream BarBar digit geometry into a small LVGL C++ header.

Usage:
  python hardware/scripts/generate_barbar_clock_assets.py
  python hardware/scripts/generate_barbar_clock_assets.py --upstream PATH

PATH must contain the original upstream LICENSE and digital_clock/lib/data/
digits_collection.dart. The default points at the saved reference archive.
"""

from __future__ import annotations

import argparse
import ast
from fractions import Fraction
from pathlib import Path
import re


REPO = Path(__file__).resolve().parents[2]
DEFAULT_UPSTREAM = (
    REPO / "design/barbar-clock-20261115/upstream"
    / "flutter-clock-challenge-barbar-master"
)


def normalized_coordinate(expression: str) -> int:
    """Evaluate only integer literals, addition and division, exactly."""
    def walk(node: ast.AST) -> Fraction:
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return Fraction(node.value)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            return walk(node.left) + walk(node.right)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
            return walk(node.left) / walk(node.right)
        raise ValueError(f"Unsupported coordinate: {expression!r}")

    value = walk(ast.parse(expression.strip(), mode="eval").body) * 128
    if value.denominator != 1 or not 0 <= value <= 128:
        raise ValueError(f"Coordinate is outside normalized geometry: {expression}")
    return int(value)


def extract_digits(source: str) -> list[list[list[tuple[int, int]]]]:
    digits: dict[int, list[list[tuple[int, int]]]] = {}
    digit_pattern = r"final List<DisplayBar> _digit_(\d) = \[(.*?)\n  \];"
    bar_pattern = r"DisplayBar\(barNumber: (\d+), startY: (.*?), endY: (.*)\),"
    for digit_text, body in re.findall(digit_pattern, source, re.S):
        columns: list[list[tuple[int, int]]] = [[] for _ in range(6)]
        for column_text, start_text, end_text in re.findall(bar_pattern, body):
            column = int(column_text)
            if not 0 <= column < 6:
                raise ValueError("Unexpected digit column")
            start = normalized_coordinate(start_text)
            end = normalized_coordinate(end_text)
            if start > end:
                raise ValueError("Bar interval has reversed endpoints")
            columns[column].append((start, end))
        for intervals in columns:
            intervals.sort()
            if not 1 <= len(intervals) <= 4:
                raise ValueError("A digit column must contain one to four intervals")
            if intervals[0][0] != 0 or intervals[-1][1] != 128:
                raise ValueError("A digit column must meet both viewport edges")
            if any(a[1] > b[0] for a, b in zip(intervals, intervals[1:])):
                raise ValueError("Overlapping digit intervals")
        digits[int(digit_text)] = columns
    if set(digits) != set(range(10)):
        raise ValueError("Source must contain the ten expected digit shapes")
    return [digits[digit] for digit in range(10)]


def render_header(digits: list[list[list[tuple[int, int]]]]) -> str:
    lines = [
        "// Generated by hardware/scripts/generate_barbar_clock_assets.py.",
        "// Original geometry: Copyright 2020 aednlaxer, BSD-3-Clause.",
        "// See barbar_clock_LICENSE.txt and barbar_clock_sources.md.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// Interior endpoints map to the digit's active height; 0 and 128",
        "// meet the top and bottom of the viewport, respectively.",
        "struct BarbarClockBarInterval { uint8_t start; uint8_t end; };",
        "",
        "static const uint8_t barbar_clock_digit_counts[10][6] = {",
    ]
    for digit, columns in enumerate(digits):
        counts = ", ".join(str(len(intervals)) for intervals in columns)
        lines.append(f"    {{{counts}}}, // {digit}")
    lines += ["};", "", "static const BarbarClockBarInterval barbar_clock_digit_segments[10][6][4] = {"]
    for digit, columns in enumerate(digits):
        lines.append(f"    {{ // {digit}")
        for intervals in columns:
            padded = intervals + [(0, 0)] * (4 - len(intervals))
            values = ", ".join(f"{{{start}, {end}}}" for start, end in padded)
            lines.append(f"        {{{values}}},")
        lines.append("    },")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM)
    parser.add_argument(
        "--out", type=Path,
        default=REPO / "hardware/arduino/yiyi_desk/src/pages/assets",
    )
    args = parser.parse_args()
    source = args.upstream / "digital_clock/lib/data/digits_collection.dart"
    digits = extract_digits(source.read_text(encoding="utf-8"))
    args.out.mkdir(parents=True, exist_ok=True)
    header = args.out / "barbar_clock_digits.h"
    header.write_text(render_header(digits), encoding="utf-8", newline="\n")
    (args.out / "barbar_clock_LICENSE.txt").write_bytes(
        (args.upstream / "LICENSE").read_bytes()
    )
    print(f"Generated {header}: 10 digits, 60 columns, "
          f"{sum(len(c) for d in digits for c in d)} intervals")


if __name__ == "__main__":
    main()
