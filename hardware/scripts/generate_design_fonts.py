"""F-d font pipeline entry point (superseded the F-b CJK generator).

Since task-11 the firmware fonts are generated by
``hardware/scripts/rebuild_fd_fonts.py`` from OFL sources (Noto Sans SC /
Noto Serif SC / Montserrat / Lilita One) with a converged size matrix and
legacy-symbol aliases.  This module is kept as the documented entry point so
existing commands keep working:

    python hardware/scripts/generate_design_fonts.py            # == rebuild_fd_fonts.py
    python hardware/scripts/generate_design_fonts.py --dry-run  # matrix + charset report

The old F-b generator (Windows msyh/segoe/georgia/kai fonts, runtime scaling via
gift_font_scale.h) was removed in F-d: those Windows fonts are not
redistributable and the scaling wrappers are gone.  ``rebuild_fd_fonts.py``
regenerates every font, the coverage header/source and the stub files for the
old per-symbol .c files (the old symbols live on as shared-array aliases).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from rebuild_fd_fonts import main as rebuild_main  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    return rebuild_main(argv)


if __name__ == "__main__":
    sys.exit(main())
