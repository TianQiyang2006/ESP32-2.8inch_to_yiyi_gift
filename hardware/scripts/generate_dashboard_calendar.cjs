// Calendar labels matching the upstream clock's first lunar/solar festival,
// falling back to the solar term. Inputs: lunar-javascript 1.7.7 (MIT).
// Run: node hardware/scripts/generate_dashboard_calendar.cjs <path/to/lunar.cjs>
const fs = require('node:fs');
const path = require('node:path');
const {Solar} = require(path.resolve(process.argv[2] || 'build/dashboard-font-source/lunar.cjs'));
const root = path.resolve(__dirname, '../..');
const dest = path.join(root, 'hardware/arduino/yiyi_desk/src/pages/assets');
const labels = [''];
const offsets = [0];
const events = [];
const lichun = [];
for (let year = 1900; year <= 2099; year++) {
  let spring = 204;
  for (let month = 1; month <= 12; month++) {
    const days = new Date(Date.UTC(year, month, 0)).getUTCDate();
    for (let day = 1; day <= days; day++) {
      const solar = Solar.fromYmd(year, month, day);
      const lunar = solar.getLunar();
      const term = lunar.getJieQi();
      if (term === '立春') spring = month * 100 + day;
      const list = [...lunar.getFestivals(), ...solar.getFestivals()];
      const label = list[0] || term;
      if (!label) continue;
      let index = labels.indexOf(label);
      if (index < 0) { index = labels.length; labels.push(label); }
      events.push([month * 100 + day, index]);
    }
  }
  offsets.push(events.length);
  lichun.push(spring);
}
const lines = [
  '// Generated by generate_dashboard_calendar.cjs; lunar-javascript 1.7.7 (MIT).',
  '#include "dashboard_clock_calendar.h"',
  'const char *const dashboard_clock_event_names[] = {',
  ...labels.map(label => ` ${JSON.stringify(label)},`),
  '};',
  `const uint16_t dashboard_clock_year_offsets[201] = {${offsets.join(',')}};`,
  `const uint16_t dashboard_clock_lichun[200] = {${lichun.join(',')}};`,
  'const DashboardClockCalendarEvent dashboard_clock_calendar_events[] = {',
];
for (let n = 0; n < events.length; n += 16) {
  lines.push(' ' + events.slice(n, n+16).map(([date, index]) => `{${date},${index}}`).join(',') + ',');
}
lines.push('};', '');
fs.writeFileSync(path.join(dest, 'dashboard_clock_calendar.c'), lines.join('\n'), 'utf8');
console.log(JSON.stringify({years:200, events:events.length, labels:labels.length}));
