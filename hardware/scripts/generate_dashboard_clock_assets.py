"""Build the clock's small, recolorable digit masks, without whole-screen frames.

Inputs are Fredoka's OFL variable font and upstream ClockDigits (Roboto Flex OFL).
Only digits and '-' are rasterized. Alpha is quantized to four bits and encoded
as runs (high nibble: count minus one; low nibble: alpha). Runtime decodes only
the selected face into PSRAM. No browser/font engine is needed by the firmware.
"""
from pathlib import Path
from io import BytesIO
import argparse
import sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'hardware/arduino/yiyi_desk/src/pages/assets'


def encode(image):
    pixels = [(x + 8) // 17 for x in image.tobytes()]
    encoded = bytearray()
    for value in pixels:
        if encoded and (encoded[-1] & 15) == value and encoded[-1] >> 4 < 15:
            encoded[-1] += 16
        else:
            encoded.append(value)
    return encoded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rounded', type=Path, default=ROOT/'build/dashboard-font-source/Fredoka.ttf')
    parser.add_argument('--compact', type=Path, default=ROOT/'build/dashboard-font-source/ClockDigits.ttf')
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    font_data = bytearray()
    faces = []
    preview = Image.new('RGB', (800, 104*3+144), '#101115')
    for face in range(10):
        compact = face == 9
        weight = (face + 1)*100
        if compact:
            font = ImageFont.truetype(str(args.compact), 160)
            width, height = 44, 144
        else:
            variable = TTFont(args.rounded)
            # Keep nine distinct UI weights in Fredoka's supported 300–700
            # range. The normal 700 UI selection uses Fredoka 600.
            instance = instantiateVariableFont(variable, {'wght': 250+weight/2, 'wdth': 100}, inplace=True)
            stream = BytesIO()
            instance.save(stream)
            stream.seek(0)
            # Render at four times the final mask size before filtering. Low
            # size hinting and four-bit alpha otherwise flatten the top crown.
            font = ImageFont.truetype(stream, 128*4)
            width, height = 80, 104
        supersample = 1 if compact else 4
        raster_width, raster_height = width*supersample, height*supersample
        boxes = [font.getbbox(str(i)) for i in range(10)]
        top = min(x[1] for x in boxes)
        bottom = max(x[3] for x in boxes)
        glyphs = []
        for digit in range(11):
            image = Image.new('L', (raster_width, raster_height))
            draw = ImageDraw.Draw(image)
            char = str(digit) if digit < 10 else '-'
            bounds = font.getbbox(char)
            # ClockDigits' 8 extends left of its advance box. Center its ink
            # bounds, including negative bearings, so no outline is cut off.
            if compact and char == '-':
                # The upstream digit-only font has an empty dash glyph.
                draw.rounded_rectangle((9, height//2-3, width-10, height//2+3), radius=3, fill=255)
            else:
                x = (raster_width-(bounds[2]-bounds[0]))/2-bounds[0]
                draw.text((x, (raster_height-(bottom-top))/2-top), char, font=font, fill=255)
            if supersample > 1:
                image = image.resize((width, height), Image.Resampling.LANCZOS)
            bbox = image.getbbox()
            assert bbox and bbox[0] > 0 and bbox[1] > 0 and bbox[2] < width and bbox[3] < height, (face, char, bbox)
            packed = encode(image)
            glyphs.append((len(font_data), len(packed)))
            font_data.extend(packed)
            if face in (0, 3, 6, 9) and digit < 10:
                row = (0, 3, 6, 9).index(face)
                tile = Image.new('RGB', image.size, '#101115')
                tile.paste('#659fe8', (0, 0, width, height), image)
                preview.paste(tile, (digit*80, row*104))
        faces.append((width, height, glyphs))
    lines = ['// Generated by generate_dashboard_clock_assets.py; see dashboard_clock_sources.md.',
             '#include "dashboard_clock_masks.h"',
             'const uint8_t dashboard_clock_mask_data[] = {']
    for i in range(0, len(font_data), 24):
        lines.append(' ' + ','.join(f'0x{x:02x}' for x in font_data[i:i+24]) + ',')
    lines.append('};\nconst DashboardClockMaskFont dashboard_clock_mask_fonts[10] = {')
    for width, height, glyphs in faces:
        lines.append(' {%d,%d,{%s}},' % (width, height, ','.join('{%d,%d}' % x for x in glyphs)))
    lines.append('};\n')
    (OUT/'dashboard_clock_masks.c').write_text('\n'.join(lines), encoding='utf-8')
    proof = ROOT/'build/dashboard-font-source/digits-preview.png'
    preview.save(proof)
    print(f'Digit alpha runs: {len(font_data):,} bytes; preview: {proof}')


if __name__ == '__main__':
    main()
